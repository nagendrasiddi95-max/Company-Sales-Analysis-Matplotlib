import matplotlib.pyplot as plt

import matplotlib.pyplot as plt

months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun']

sales = [12000, 15000, 18000, 14000, 22000, 25000]

profit = [2000, 3000, 4000, 2500, 5000, 6000]

categories = ['Electronics', 'Clothing', 'Food', 'Furniture']

category_sales = [40000, 25000, 20000, 15000]

plt.plot(months ,sales)
plt.title('Monthly Sales Analysis')
plt.xlabel('Months')
plt.ylabel('Sales')
plt.grid(True)
plt.show(
)

plt.bar(months,profit,color=['red','green','blue','yellow','skyblue','brown'])
plt.title('Monthly Profit Analysis')
plt.xlabel('Months')
plt.ylabel('Profit')
plt.grid(True)
plt.show()

plt.pie(category_sales,labels=categories,autopct='%1.1f%%')
plt.title('Sales by Category')
plt.show()

plt.hist(sales,bins=5,edgecolor='black')
plt.title('Sales Distribution')
plt.xlabel('Sales')
plt.ylabel('Frequency')
plt.grid(True)
plt.show()

plt.scatter(sales,profit,color ='red')
plt.title('Sales vs Profit Scatter Plot')
plt.xlabel('Sales')
plt.ylabel('Profit')
plt.grid(True)
plt.show()

